#!/usr/bin/env python3
"""Writes quickshell/LayoutPreviews.js: what each of the three methods does
to the same three, four and six windows, computed by the real algorithms
(the Settings cards draw these, so the picture is the method, not a
drawing of it):

  galaxy     dxrice_spiral.arrange
  compact    dxrice_compact.auto_arrange (it resizes; the sizes it picks show)
  expansion  dxrice_expansion.arrange

All three may reach past the screen, so each preview is framed on the
whole arrangement and carries the screen's outline (`screens`). Every
number is 0..1 of the preview's frame. `--check` exits 1 if the file is out
of date.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dxrice_compact  # noqa: E402
import dxrice_expansion  # noqa: E402
import dxrice_spiral  # noqa: E402

OUT = os.path.join(HERE, "..", "quickshell", "LayoutPreviews.js")
SCREEN = (0, 0, 1920, 1080)
ASPECT = 1.6                   # the Settings card's preview area
# ordinary window sizes, in the order they were opened, and where they
# start for the methods that look at that (a loose cascade)
SIZES = [(1100, 700), (900, 600), (820, 540), (760, 520), (700, 480), (660, 440)]
START = [(200 + 160 * i, 120 + 90 * i) for i in range(len(SIZES))]
BAND = (dxrice_spiral.SPACING_MIN_DEFAULT, dxrice_spiral.SPACING_MAX_DEFAULT)
MODES = ("galaxy", "compact", "expansion")


def rects(mode, n):
    """(x0, y0, x1, y1) per window, in opening order."""
    sizes, start = SIZES[:n], START[:n]
    if mode == "galaxy":
        return list(dxrice_spiral.arrange(sizes, [], SCREEN, BAND))
    if mode == "compact":
        eligible = [{"address": f"0x{i}", "at": list(p), "size": list(s), "class": f"app{i}", "pid": 100 + i}
                    for i, (p, s) in enumerate(zip(start, sizes))]
        by = {a: (x, y, x + w, y + h) for a, x, y, w, h in dxrice_compact.auto_arrange(eligible, [], SCREEN, 5)}
        return [by[f"0x{i}"] for i in range(n)]
    return dxrice_expansion.arrange([(x, y, w, h) for (x, y), (w, h) in zip(start, sizes)], [], SCREEN, BAND)


def framed(boxes):
    """(rects, screen) as 0..1 of a frame holding the screen and every
    window at the card's aspect ratio, centred."""
    allb = [SCREEN] + list(boxes)
    x0, y0 = min(b[0] for b in allb), min(b[1] for b in allb)
    x1, y1 = max(b[2] for b in allb), max(b[3] for b in allb)
    w, h = x1 - x0, y1 - y0
    if w / h < ASPECT:
        x0 -= (h * ASPECT - w) / 2
        w = h * ASPECT
    else:
        y0 -= (w / ASPECT - h) / 2
        h = w / ASPECT

    def rel(b):
        return ((b[0] - x0) / w, (b[1] - y0) / h, (b[2] - b[0]) / w, (b[3] - b[1]) / h)
    return [rel(b) for b in boxes], rel(SCREEN)


def _fmt(r):
    return "[%.4f, %.4f, %.4f, %.4f]" % tuple(r)


def render():
    lines = [".pragma library", "",
             "// Generated by scripts/dxrice_gen_layout_previews.py from the real algorithms",
             "// (dxrice_spiral, dxrice_compact, dxrice_expansion). Do not edit: run the",
             "// script (a test fails when this is out of date).",
             "// rects: {method: {count: [[x, y, w, h], ...]}}; screens: the screen's outline",
             "// in the same frame. Every number is 0..1 of the preview's frame.",
             "var rects = {"]
    screens = {}
    for mi, mode in enumerate(MODES):
        lines.append(f"    {mode}: {{")
        screens[mode] = {}
        for ci, n in enumerate((3, 4, 6)):
            rs, scr = framed(rects(mode, n))
            screens[mode][n] = scr
            lines.append(f"        {n}: [{', '.join(_fmt(r) for r in rs)}]" + ("," if ci < 2 else ""))
        lines.append("    }" + ("," if mi < len(MODES) - 1 else ""))
    lines += ["};", "", "var screens = {"]
    for mi, mode in enumerate(MODES):
        lines.append(f"    {mode}: {{" + ", ".join(f"{n}: {_fmt(screens[mode][n])}" for n in (3, 4, 6)) + "}"
                     + ("," if mi < len(MODES) - 1 else ""))
    lines += ["};", "",
              'var modes = ["galaxy", "compact", "expansion"];',
              'var names = { galaxy: "Galaxy Spiral", compact: "Compact", expansion: "Expansion" };',
              "var blurbs = {",
              '    galaxy: "Windows keep their size and grow outward in a spiral across the infinite desktop.",',
              '    compact: "A tight, balanced cluster; windows are resized a little where that packs them better.",',
              '    expansion: "Windows keep their size and burst outward from the centre, each in its own direction.",',
              "};", ""]
    return "\n".join(lines)


def main(argv):
    text = render()
    path = os.path.normpath(OUT)
    if "--check" in argv:
        try:
            ok = open(path).read() == text
        except OSError:
            ok = False
        if not ok:
            print("quickshell/LayoutPreviews.js is out of date: run scripts/dxrice_gen_layout_previews.py")
        return 0 if ok else 1
    with open(path, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
