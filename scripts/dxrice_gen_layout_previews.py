#!/usr/bin/env python3
"""Writes quickshell/LayoutPreviews.js: what each layout does to three, four
and six windows, as 0..1 rectangles, computed by the real layout code (the
Settings cards draw these, so the picture is the layout, not a drawing of
it). The Galaxy Spiral comes from dxrice_spiral itself: windows keep their
size and the cloud reaches past the screen, so its preview is framed on the
whole cloud and carries the screen's outline (`screens`). `--check` exits 1
if the file is out of date.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dxrice_layouts  # noqa: E402
import dxrice_spiral  # noqa: E402

OUT = os.path.join(HERE, "..", "quickshell", "LayoutPreviews.js")
AREA = (0, 0, 1600, 1000)
GAP = 24                       # drawn gaps: a preview's gaps must be visible
# the Galaxy preview: a 1920x1080 screen and ordinary window sizes, in the
# order they were opened (the first is the spiral's anchor)
SCREEN = (0, 0, 1920, 1080)
GALAXY_SIZES = [(1100, 700), (900, 600), (820, 540), (760, 520), (700, 480), (660, 440)]
ASPECT = (AREA[2] - AREA[0]) / (AREA[3] - AREA[1])


def galaxy(n):
    """(rects, screen) for n windows of the Galaxy Spiral, both 0..1 of a
    view box that holds the screen and the whole cloud at the preview's
    aspect ratio."""
    placed = dxrice_spiral.arrange(GALAXY_SIZES[:n], [], SCREEN,
                                   (dxrice_spiral.SPACING_MIN_DEFAULT, dxrice_spiral.SPACING_MAX_DEFAULT))
    boxes = [SCREEN] + list(placed)
    x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
    x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
    w, h = x1 - x0, y1 - y0
    if w / h < ASPECT:                       # widen or heighten to the card's shape, centred
        x0 -= (h * ASPECT - w) / 2
        w = h * ASPECT
    else:
        y0 -= (w / ASPECT - h) / 2
        h = w / ASPECT

    def rel(b):
        return ((b[0] - x0) / w, (b[1] - y0) / h, (b[2] - b[0]) / w, (b[3] - b[1]) / h)
    return [rel(b) for b in placed], rel(SCREEN)


def _fmt(r):
    return "[%.4f, %.4f, %.4f, %.4f]" % tuple(r)


def render():
    lines = [".pragma library", "",
             "// Generated by scripts/dxrice_gen_layout_previews.py from scripts/dxrice_layouts.py and dxrice_spiral.py.",
             "// Do not edit: run the script (the test fails when this is out of date).",
             "// {mode: {count: [[x, y, w, h], ...]}}, every number 0..1 of the area.",
             "var rects = {"]
    w, h = AREA[2] - AREA[0], AREA[3] - AREA[1]
    lines.append("    galaxy: {")
    for ci, n in enumerate((3, 4, 6)):
        rects, _screen = galaxy(n)
        lines.append(f"        {n}: [{', '.join(_fmt(r) for r in rects)}]" + ("," if ci < 2 else ""))
    lines.append("    },")
    for mi, mode in enumerate(dxrice_layouts.MODES):
        lines.append(f"    {mode}: {{")
        for ci, n in enumerate((3, 4, 6)):
            rects = dxrice_layouts.layout(mode, n, AREA, GAP, n - 1, 200, 140)
            body = ", ".join("[%.4f, %.4f, %.4f, %.4f]" % (r[0] / w, r[1] / h, r[2] / w, r[3] / h)
                             for r in rects if r)
            lines.append(f"        {n}: [{body}]" + ("," if ci < 2 else ""))
        lines.append("    }" + ("," if mi < len(dxrice_layouts.MODES) - 1 else ""))
    lines += ["};", "",
              "// The screen's outline inside a preview that reaches past it (Galaxy only).",
              "var screens = {",
              "    galaxy: {" + ", ".join(f"{n}: {_fmt(galaxy(n)[1])}" for n in (3, 4, 6)) + "}",
              "};", "",
              'var modes = ["galaxy", "expansion", "spiral", "compact"];',
              'var names = { galaxy: "Galaxy Spiral", expansion: "Expansion", spiral: "Spiral", compact: "Compact" };',
              "var blurbs = {",
              '    galaxy: "Windows keep their size and spiral outward across the infinite desktop.",',
              '    expansion: "The newest or focused window gets the room; the rest share what is left.",',
              '    spiral: "Each window takes half of what remains, turning clockwise.",',
              '    compact: "An even grid. Nobody gets a bigger share.",',
              "};", ""]
    return "\n".join(lines)


def main(argv):
    text = render()
    path = os.path.normpath(OUT)
    if "--check" in argv:
        try:
            ok = open(path).read() == text
        except OSError:
            ok = False
        if not ok:
            print("quickshell/LayoutPreviews.js is out of date: run scripts/dxrice_gen_layout_previews.py")
        return 0 if ok else 1
    with open(path, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
