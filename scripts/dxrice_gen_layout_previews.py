#!/usr/bin/env python3
"""Writes quickshell/LayoutPreviews.js: what each layout does to four and to
six windows, as 0..1 rectangles, computed by the real layout code (the
Settings cards draw these, so the picture is the layout, not a drawing of
it). `--check` exits 1 if the file is out of date.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dxrice_layouts  # noqa: E402

OUT = os.path.join(HERE, "..", "quickshell", "LayoutPreviews.js")
AREA = (0, 0, 1600, 1000)
GAP = 24                       # drawn gaps: a preview's gaps must be visible


def render():
    lines = [".pragma library", "",
             "// Generated by scripts/dxrice_gen_layout_previews.py from scripts/dxrice_layouts.py.",
             "// Do not edit: run the script (the test fails when this is out of date).",
             "// {mode: {count: [[x, y, w, h], ...]}}, every number 0..1 of the area.",
             "var rects = {"]
    w, h = AREA[2] - AREA[0], AREA[3] - AREA[1]
    for mi, mode in enumerate(dxrice_layouts.MODES):
        lines.append(f"    {mode}: {{")
        for ci, n in enumerate((3, 4, 6)):
            rects = dxrice_layouts.layout(mode, n, AREA, GAP, n - 1, 200, 140)
            body = ", ".join("[%.4f, %.4f, %.4f, %.4f]" % (r[0] / w, r[1] / h, r[2] / w, r[3] / h)
                             for r in rects if r)
            lines.append(f"        {n}: [{body}]" + ("," if ci < 2 else ""))
        lines.append("    }" + ("," if mi < len(dxrice_layouts.MODES) - 1 else ""))
    lines += ["};", "",
              'var modes = ["expansion", "spiral", "compact"];',
              'var names = { expansion: "Expansion", spiral: "Spiral", compact: "Compact" };',
              "var blurbs = {",
              '    expansion: "The newest or focused window gets the room; the rest share what is left.",',
              '    spiral: "Each window takes half of what remains, turning clockwise.",',
              '    compact: "An even grid. Nobody gets a bigger share.",',
              "};", ""]
    return "\n".join(lines)


def main(argv):
    text = render()
    path = os.path.normpath(OUT)
    if "--check" in argv:
        try:
            ok = open(path).read() == text
        except OSError:
            ok = False
        if not ok:
            print("quickshell/LayoutPreviews.js is out of date: run scripts/dxrice_gen_layout_previews.py")
        return 0 if ok else 1
    with open(path, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
